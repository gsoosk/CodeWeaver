def validate_citation_catalog() -> None:
    if len(CITATION_RECORDS) != 30:
        raise ValueError("citation census must contain exactly 30 index records")
    counts: dict[str, int] = {}
    for row in CITATION_RECORDS:
        classification = row["classification"]
        counts[classification] = counts.get(classification, 0) + 1
    if counts != {
        "in_scope": 19,
        "tangential": 8,
        "out_of_scope": 1,
        "duplicate": 2,
    }:
        raise ValueError(f"citation census classification drifted: {counts}")
    if len(INCLUSION_MATRIX) != 20 or len({row["key"] for row in INCLUSION_MATRIX}) != 20:
        raise ValueError("inclusion matrix must contain 19 unique in-scope works plus TACO")
    if len(ORBIT_SUBJECTS) != 24 or len({row["project_id"] for row in ORBIT_SUBJECTS}) != 24:
        raise ValueError("ORBIT exact-subject lock drifted")
    if sum(bool(row["orbit_ext_test"]) for row in ORBIT_SUBJECTS) != 22:
        raise ValueError("ORBIT expert-interface reference drifted")
    if sum(bool(row["orbit_gen_test"]) for row in ORBIT_SUBJECTS) != 22:
        raise ValueError("ORBIT generated-interface reference drifted")
    if len(ACTOR_PUBLIC_MISSING_PROJECT_IDS) != 5:
        raise ValueError("ACTOR public-artifact 95-project boundary drifted")
    surface_keys = {row["key"] for row in CITER_SURFACES}
    expected_keys = {row["key"] for row in INCLUSION_MATRIX}
    if surface_keys != expected_keys:
        raise ValueError(
            f"citer surface inventory drifted: missing={expected_keys-surface_keys}, "
            f"extra={surface_keys-expected_keys}"
        )


