def _elapsed_seconds(state: dict[str, Any]) -> float | None:
    if not state.get("started_at") or not state.get("ended_at"):
        return None
    try:
        started = datetime.fromisoformat(
            str(state["started_at"]).replace("Z", "+00:00")
        )
        ended = datetime.fromisoformat(
            str(state["ended_at"]).replace("Z", "+00:00")
        )
    except ValueError:
        return None
    return max(0.0, (ended - started).total_seconds())


def _usage(run_dir: Path) -> dict[str, Any]:
    paths = sorted((run_dir / "pipeline" / "logs").glob("*.stdout.jsonl"))
    totals = {
        "assistant_turns": 0,
        "tool_invocations": 0,
        "input_tokens": 0,
        "output_tokens": 0,
        "nano_aiu": 0,
        "premium_requests": 0,
    }
    seen = {key: False for key in totals}
    for path in paths:
        events = parse_copilot_jsonl(
            path.read_text(encoding="utf-8", errors="replace")
        )
        summary = summarize_copilot_events(events)
        for key in ("assistant_turns", "tool_invocations"):
            totals[key] += int(getattr(summary, key))
            seen[key] = True
        for key in (
            "input_tokens",
            "output_tokens",
            "nano_aiu",
            "premium_requests",
        ):
            value = getattr(summary, key)
            if value is not None:
                totals[key] += int(value)
                seen[key] = True
    return {
        f"total_{key}": totals[key] if seen[key] else None for key in totals
    }


def _candidate_payload_files(candidate: Path) -> list[Path]:
    files: list[Path] = []
    pending = [candidate]
    while pending:
        directory = pending.pop()
        for path in sorted(directory.iterdir(), reverse=True):
            relative = path.relative_to(candidate)
            if path.is_symlink():
                raise ValueError(f"candidate symlink rejected: {relative}")
            if path.is_dir():
                if path.name not in CANDIDATE_EXCLUDED_DIRS:
                    pending.append(path)
                continue
            if not path.is_file():
                raise ValueError(f"candidate special file rejected: {relative}")
            if path.stat().st_nlink != 1:
                raise ValueError(f"candidate hard link rejected: {relative}")
            if path.suffix.lower() in CANDIDATE_NATIVE_SUFFIXES:
                raise ValueError(f"candidate native artifact rejected: {relative}")
            if path.name == "build.rs":
                raise ValueError("candidate build.rs rejected")
            files.append(path)
    files.sort()
    return files


def _validate_candidate_root(candidate: Path, run_dir: Path) -> None:
    if candidate.is_symlink():
        raise ValueError("candidate root symlink rejected")
    if not candidate.is_dir():
        raise ValueError("candidate directory missing")
    try:
        candidate.resolve(strict=True).relative_to(run_dir.resolve(strict=True))
    except ValueError as exc:
        raise ValueError("candidate root escapes its run directory") from exc
    cargo_toml = candidate / "Cargo.toml"
    if not cargo_toml.is_file() or cargo_toml.is_symlink():
        raise ValueError("candidate Cargo.toml missing or linked")
    cargo_text = cargo_toml.read_text(encoding="utf-8", errors="replace")
    if re.search(r"(?m)^\s*build\s*=", cargo_text) or re.search(
        r"(?m)^\s*\[build-dependencies(?:\.[^\]]+)?\]\s*$",
        cargo_text,
    ):
        raise ValueError("candidate build script configuration rejected")
    _candidate_payload_files(candidate)


def _copy_candidate_payload(candidate: Path, destination: Path) -> None:
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    for source in _candidate_payload_files(candidate):
        relative = source.relative_to(candidate)
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)


def _rust_source_metrics(candidate: Path) -> tuple[int, int, int]:
    files = sorted(candidate.rglob("*.rs"))
    unsafe_count = 0
    delegation_count = 0
    for path in files:
        text = _mask_rust(path.read_text(encoding="utf-8", errors="replace"))
        unsafe_count += len(re.findall(r"\bunsafe\b", text))
        delegation_count += sum(
            len(pattern.findall(text)) for pattern in DELEGATION_PATTERNS
        )
    return len(files), unsafe_count, delegation_count


def _runtime_libraries(binary: Path) -> list[Path]:
    result = C.run_command(["ldd", str(binary)], cwd=binary.parent, timeout=120)
    if result["returncode"] != 0:
        diagnostic = (result["stdout"] + "\n" + result["stderr"])[-2000:]
        raise RuntimeError(f"failed to inspect candidate runtime libraries:\n{diagnostic}")
    libraries: set[Path] = set()
    for line in result["stdout"].splitlines():
        if "not found" in line:
            raise RuntimeError(f"candidate runtime dependency unresolved: {line}")
        match = re.search(r"(?:=>\s+)?(/[^\s()]+)", line)
        if match:
            libraries.add(Path(match.group(1)))
    return sorted(libraries)


def _isolated_launcher(
    *,
    binary: Path,
    oracle: Path,
    sandbox_root: Path,
) -> Path:
    rootfs = sandbox_root / "rootfs"
    (rootfs / "work").mkdir(parents=True)
    (rootfs / "aliases").mkdir()
    (rootfs / "tmp").mkdir()
    (rootfs / "dev").mkdir()
    (rootfs / "proc").mkdir()
    (rootfs / "hidden").mkdir()
    shutil.copy2(binary, rootfs / "candidate")
    (rootfs / "candidate").chmod(0o755)
    entry_source = sandbox_root / "chroot-entry.c"
    entry_binary = sandbox_root / "chroot-entry"
    C.atomic_write_text(
        entry_source,
        """\
#include <stdio.h>
#include <errno.h>
#include <linux/capability.h>
#include <linux/securebits.h>
#include <sys/prctl.h>
#include <sys/syscall.h>
#include <unistd.h>

int main(int argc, char **argv) {
    if (argc < 3 || chdir("/work") != 0) {
        perror("actor-li chdir");
        return 125;
    }
    for (int capability = 0; capability <= CAP_LAST_CAP; capability++) {
        if (prctl(PR_CAPBSET_DROP, capability, 0, 0, 0) != 0 &&
            errno != EINVAL) {
            perror("actor-li capability bound");
            return 125;
        }
    }
    if (prctl(PR_SET_SECUREBITS,
              SECBIT_NOROOT | SECBIT_NOROOT_LOCKED |
              SECBIT_NO_SETUID_FIXUP | SECBIT_NO_SETUID_FIXUP_LOCKED,
              0, 0, 0) != 0) {
        perror("actor-li securebits");
        return 125;
    }
    struct __user_cap_header_struct header = {
        _LINUX_CAPABILITY_VERSION_3, 0
    };
    struct __user_cap_data_struct capabilities[2] = {{0}};
    if (syscall(SYS_capset, &header, &capabilities) != 0 ||
        prctl(PR_SET_NO_NEW_PRIVS, 1, 0, 0, 0) != 0) {
        perror("actor-li capability clear");
        return 125;
    }
    execv(argv[1], &argv[2]);
    perror("actor-li exec");
    return 125;
}
""",
    )
    entry_build = C.run_command(
        ["cc", "-O2", "-o", str(entry_binary), str(entry_source)],
        cwd=sandbox_root,
        timeout=120,
        env={"LC_ALL": "C"},
    )
    if entry_build["returncode"] != 0:
        diagnostic = (
            entry_build["stdout"] + "\n" + entry_build["stderr"]
        )[-2000:]
        raise RuntimeError(f"failed to build chroot entry helper:\n{diagnostic}")
    shutil.copy2(entry_binary, rootfs / "entry")
    (rootfs / "entry").chmod(0o755)
    libraries = set(_runtime_libraries(binary))
    libraries.update(_runtime_libraries(entry_binary))
    for library in sorted(libraries):
        destination = rootfs / library.relative_to("/")
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(library.resolve(), destination)
    locale_root = Path("/usr/lib/locale/C.utf8")
    if locale_root.is_dir():
        shutil.copytree(
            locale_root,
            rootfs / "usr" / "lib" / "locale" / "C.utf8",
        )
    locale_alias = Path("/etc/locale.alias")
    if locale_alias.is_file():
        destination = rootfs / "etc" / "locale.alias"
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(locale_alias, destination)
    protected = [
        path.name
        for path in sorted(oracle.iterdir())
        if path.is_file() or path.is_symlink()
    ]
    C.atomic_write_text(
        rootfs / "protected-files.txt",
        "".join(f"{name}\n" for name in protected),
    )
    launcher = sandbox_root / "isolated-candidate"
    script = f"""\
#!/usr/bin/env bash
set -euo pipefail
root={shlex.quote(str(rootfs.resolve()))}
work=$PWD
program_name=$0
alias_name=$(basename "$0")
case "$alias_name" in
  ""|"."|".."|*/*) exit 125 ;;
esac
exec /usr/bin/unshare --mount --pid --fork -- /usr/bin/bash -c '
set -euo pipefail
root=$1
work=$2
alias_name=$3
program_name=$4
shift 4
/usr/bin/mount --make-rprivate /
/usr/bin/mount --bind "$work" "$root/work"
/usr/bin/mount -t proc proc "$root/proc"
index=0
while IFS= read -r relative; do
  [ -n "$relative" ] || continue
  target="$root/work/$relative"
  if [ -e "$target" ] || [ -L "$target" ]; then
    hidden="$root/hidden/$index"
    : > "$hidden"
    /usr/bin/mount --bind "$hidden" "$target"
    /usr/bin/mount -o remount,bind,ro "$target"
    index=$((index + 1))
  fi
done < "$root/protected-files.txt"
: > "$root/dev/null"
/usr/bin/mount --bind /dev/null "$root/dev/null"
if [ -b /dev/sda ]; then
  : > "$root/dev/sda"
  /usr/bin/mount --bind /dev/sda "$root/dev/sda"
fi
/usr/bin/ln -f "$root/candidate" "$root/aliases/$alias_name"
for variable in $(compgen -e); do
  case "$variable" in
    *TOKEN*|*token*|*SECRET*|*secret*|*PASSWORD*|*password*|*PASSWD*|*passwd*|\
*CREDENTIAL*|*credential*|*API_KEY*|*api_key*|*AUTH*|*auth*)
      unset "$variable"
      ;;
  esac
done
export PATH=/nonexistent HOME=/work TMPDIR=/tmp
exec /usr/sbin/chroot "$root" /entry "/aliases/$alias_name" "$program_name" "$@"
' actor-li-sandbox "$root" "$work" "$alias_name" "$program_name" "$@"
"""
    C.atomic_write_text(launcher, script)
    launcher.chmod(0o755)
    return launcher


def _sandboxed_comparison(
    *,
    binary: Path,
    oracle: Path,
    sandbox_root: Path,
    timeout: float,
) -> dict[str, Any]:
    launcher = _isolated_launcher(
        binary=binary,
        oracle=oracle,
        sandbox_root=sandbox_root,
    )
    return C.run_command(
        ["bash", "./testcmp.sh", "compare", str(launcher.resolve())],
        cwd=oracle,
        timeout=timeout,
    )


def evaluate_run(
    subject: dict[str, Any],
    *,
    repetition: int,
    artifact_root: Path,
    workspace_root: Path,
    runs_root: Path,
    output_root: Path,
) -> dict[str, Any]:
    name = subject["name"]
    subject_id = _subject_id(name)
    run_dir = runs_root / "full" / subject_id / f"rep{repetition}"
    candidate = run_dir / "pipeline" / "target"
    state = _state(run_dir)
    usage = _usage(run_dir)
    terminal = state.get("status") in TERMINAL_STATUSES
    expected = subject["validation_tests"]
    prepared = C.read_json(workspace_root / subject_id / "prepared.json")
    validation = artifact_root / "validation_tests" / name
    actual_contract_hash = _tree_sha256(validation)
    row: dict[str, Any] = {
        "campaign": "actor-li-absolute-micro",
        "subject_id": subject_id,
        "subject": name,
        "repetition": repetition,
        "run_status": state.get("status", "missing"),
        "evaluation_status": "measured" if terminal else "not_measured",
        "candidate_status": "missing_candidate",
        "expected_tests": expected,
        "tests_loaded": 0,
        "tests_passed": 0,
        "tests_failed": 0,
        "tests_not_executed": expected,
        "build": False,
        "pass_all": False,
        "safe_rust": False,
        "self_contained": False,
        "safe_pass_all": False,
        "unsafe_tokens": 0,
        "delegation_tokens": 0,
        "rust_source_files": 0,
        "candidate_runtime_isolated": False,
        "validation_tree_sha256": actual_contract_hash,
        "contract_integrity": (
            actual_contract_hash == prepared["validation_tree_sha256"]
        ),
        "artifact_commit": ARTIFACT_COMMIT,
        "app_id": state.get("app_id", ""),
        "started_at": state.get("started_at", ""),
        "ended_at": state.get("ended_at", ""),
        "pipeline_error": state.get("error", ""),
        "elapsed_seconds": _elapsed_seconds(state),
        **usage,
    }
    if not terminal:
        return row
    if not row["contract_integrity"]:
        row["candidate_status"] = "contract_integrity_failed"
        return row
    if not candidate.is_dir():
        return row
    try:
        _validate_candidate_root(candidate, run_dir)
    except (OSError, ValueError) as exc:
        row["candidate_status"] = "candidate_integrity_rejected"
        row["candidate_integrity_error"] = str(exc)
        return row

    generated = output_root / "generated" / subject_id / f"rep{repetition}"
    _copy_candidate_payload(candidate, generated)
    rust_files, unsafe, delegation = _rust_source_metrics(generated)
    row.update(
        {
            "rust_source_files": rust_files,
            "unsafe_tokens": unsafe,
            "delegation_tokens": delegation,
            "safe_rust": rust_files > 0 and unsafe == 0,
            "self_contained": rust_files > 0 and delegation == 0,
        }
    )
    if delegation:
        row["candidate_status"] = "candidate_delegation_rejected"
        return row
    log_root = output_root / "logs" / subject_id / f"rep{repetition}"
    with tempfile.TemporaryDirectory(prefix=f"actor-li-{name}-eval-") as temp:
        root = Path(temp)
        candidate_copy = root / "candidate"
        oracle = root / "oracle"
        C.copytree_clean(generated, candidate_copy)
        shutil.copytree(validation, oracle)
        _normalize_shell_scripts(oracle)
        build = C.run_command(
            ["cargo", "build", "--release"],
            cwd=candidate_copy,
            timeout=1800,
            env={"CARGO_TERM_COLOR": "never"},
        )
        _write_command_log(log_root, "candidate-build", build)
        row["build"] = build["returncode"] == 0
        row["build_returncode"] = build["returncode"]
        if not row["build"]:
            row["candidate_status"] = "build_failed"
            return row
        binary = candidate_copy / "target" / "release" / name
        if not binary.is_file():
            executable = binary.with_suffix(".exe")
            if executable.is_file():
                binary = executable
            else:
                row["candidate_status"] = "missing_binary"
                return row
        oracle_build = C.run_command(["make", "all"], cwd=oracle, timeout=300)
        _write_command_log(log_root, "oracle-build", oracle_build)
        if oracle_build["returncode"] != 0:
            row["candidate_status"] = "oracle_build_failed"
            row["oracle_build_returncode"] = oracle_build["returncode"]
            return row
        comparison = _sandboxed_comparison(
            binary=binary,
            oracle=oracle,
            sandbox_root=root / "sandbox",
            timeout=900,
        )
        row["candidate_runtime_isolated"] = True
        _write_command_log(log_root, "hidden-comparison", comparison)
        counts = _parse_test_output(
            comparison["stdout"] + "\n" + comparison["stderr"]
        )
    row.update(
        {
            "candidate_status": "evaluated",
            "test_returncode": comparison["returncode"],
            "tests_loaded": counts["loaded"],
            "tests_passed": counts["passed"],
            "tests_failed": counts["failed"],
            "tests_not_executed": max(0, expected - counts["total"]),
        }
    )
    row["pass_all"] = bool(
        row["build"]
        and comparison["returncode"] == 0
        and counts["loaded"] == expected
        and counts["total"] == expected
        and counts["passed"] == expected
        and counts["failed"] == 0
    )
    row["safe_pass_all"] = bool(
        row["pass_all"] and row["safe_rust"] and row["self_contained"]
    )
    return row


def _aggregate(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    def total_with_status(
        selected: list[dict[str, Any]], field: str
    ) -> tuple[float | int | None, str, int]:
        values = [
            row[field]
            for row in selected
            if row.get(field) not in (None, "")
        ]
        status = (
            "measured"
            if len(values) == len(selected)
            else "partial"
            if values
            else "unavailable"
        )
        return (sum(values) if values else None), status, len(values)

    aggregates: list[dict[str, Any]] = []
    groups: list[tuple[str, list[dict[str, Any]]]] = [
        (
            subject["name"],
            [row for row in rows if row["subject"] == subject["name"]],
        )
        for subject in SUBJECTS
    ]
    groups.append(("ALL", rows))
    for name, selected in groups:
        aggregate = {
            "subject": name,
            "cells": len(selected),
            "measured_cells": sum(
                row["evaluation_status"] == "measured" for row in selected
            ),
            "build_cells": sum(bool(row["build"]) for row in selected),
            "pass_all_cells": sum(bool(row["pass_all"]) for row in selected),
            "safe_cells": sum(bool(row["safe_rust"]) for row in selected),
            "self_contained_cells": sum(
                bool(row["self_contained"]) for row in selected
            ),
            "safe_pass_all_cells": sum(
                bool(row["safe_pass_all"]) for row in selected
            ),
            "tests_passed": sum(int(row["tests_passed"]) for row in selected),
            "tests_expected": sum(
                int(row["expected_tests"]) for row in selected
            ),
            "test_rate_percent": (
                100
                * sum(int(row["tests_passed"]) for row in selected)
                / sum(int(row["expected_tests"]) for row in selected)
                if selected
                else 0
            ),
        }
        for output_field, source_field in (
            ("elapsed_seconds", "elapsed_seconds"),
            ("output_tokens", "total_output_tokens"),
            ("nano_aiu", "total_nano_aiu"),
            ("premium_requests", "total_premium_requests"),
        ):
            total, status, measured_cells = total_with_status(
                selected, source_field
            )
            aggregate[output_field] = total
            aggregate[f"{output_field}_status"] = status
            aggregate[f"{output_field}_measured_cells"] = measured_cells
        aggregates.append(aggregate)
    return aggregates


def _seal_terminal_matrix(
    *,
    runs_root: Path,
    output_root: Path,
    repetitions: int,
) -> dict[str, Any]:
    cells: list[dict[str, Any]] = []
    incomplete: list[str] = []
    for subject in SUBJECTS:
        subject_id = _subject_id(subject["name"])
        for repetition in range(repetitions):
            state_path = (
                runs_root
                / "full"
                / subject_id
                / f"rep{repetition}"
                / "recodeagent_run_state.json"
            )
            state = (
                C.read_json(state_path)
                if state_path.is_file()
                else {"status": "missing"}
            )
            key = f"{subject_id}/rep{repetition}"
            if state.get("status") not in TERMINAL_STATUSES:
                incomplete.append(f"{key}:{state.get('status', 'missing')}")
            cells.append(
                {
                    "subject_id": subject_id,
                    "repetition": repetition,
                    "status": state.get("status", "missing"),
                    "state_path": str(state_path),
                    "state_sha256": (
                        C.sha256_file(state_path) if state_path.is_file() else None
                    ),
                }
            )
    if incomplete:
        raise RuntimeError(
            "refusing to expose the hidden ACToR contract before every model "
            f"cell is terminal: {', '.join(incomplete)}"
        )
    seal = {
        "schema_version": 1,
        "sealed_at": C.utcnow_iso(),
        "purpose": (
            "permanently closes this campaign to further model runs before "
            "hidden-oracle evaluation"
        ),
        "cells": cells,
        "cell_count": len(cells),
    }
    path = output_root / CAMPAIGN_SEAL
    if path.is_file():
        existing = C.read_json(path)
        comparable_existing = [
            {
                key: row.get(key)
                for key in (
                    "subject_id",
                    "repetition",
                    "status",
                    "state_sha256",
                )
            }
            for row in existing.get("cells", [])
        ]
        comparable_current = [
            {
                key: row.get(key)
                for key in (
                    "subject_id",
                    "repetition",
                    "status",
                    "state_sha256",
                )
            }
            for row in cells
        ]
        if comparable_existing != comparable_current:
            raise RuntimeError(
                "ACToR run states changed after the campaign was sealed"
            )
        return existing
    C.atomic_write_json(path, seal)
    return seal


def evaluate_campaign(
    *,
    artifact_root: Path,
    workspace_root: Path,
    runs_root: Path,
    output_root: Path,
    repetitions: int = 3,
    jobs: int = 1,
) -> list[dict[str, Any]]:
    if repetitions != PROTOCOL["repetitions"]:
        raise ValueError(
            f"ACToR requires exactly {PROTOCOL['repetitions']} repetitions"
        )
    _verify_clean_artifact(artifact_root)
    (output_root / "metadata").mkdir(parents=True, exist_ok=True)
    seal = _seal_terminal_matrix(
        runs_root=runs_root,
        output_root=output_root,
        repetitions=repetitions,
    )
    shutil.copy2(
        artifact_root / "LICENSE",
        output_root / "metadata" / "ACToR-MIT.txt",
    )
    qualification = qualify_oracles(
        artifact_root=artifact_root,
        output_root=output_root / "oracle-qualification",
    )
    negative_controls = _evaluate_negative_controls(
        artifact_root=artifact_root,
        workspace_root=workspace_root,
        output_root=output_root,
    )
    tasks = [
        (subject, repetition)
        for subject in SUBJECTS
        for repetition in range(repetitions)
    ]

    def evaluate(task: tuple[dict[str, Any], int]) -> dict[str, Any]:
        subject, repetition = task
        return evaluate_run(
            subject,
            repetition=repetition,
            artifact_root=artifact_root,
            workspace_root=workspace_root,
            runs_root=runs_root,
            output_root=output_root,
        )

    if jobs <= 1:
        rows = [evaluate(task) for task in tasks]
    else:
        with ThreadPoolExecutor(max_workers=jobs) as pool:
            rows = list(pool.map(evaluate, tasks))
    fields = sorted({key for row in rows for key in row})
    C.write_csv(output_root / "raw_runs.csv", rows, fields)
    C.atomic_write_text(
        output_root / "raw_runs.jsonl",
        "".join(json.dumps(row, sort_keys=True) + "\n" for row in rows),
    )
    aggregates = _aggregate(rows)
    C.write_csv(output_root / "aggregate.csv", aggregates, list(aggregates[0]))
    expected_rows = len(SUBJECTS) * repetitions
    complete = bool(
        len(rows) == expected_rows
        and all(row["evaluation_status"] == "measured" for row in rows)
        and all(row["contract_integrity"] for row in rows)
        and qualification["status"] == "passed"
        and all(row["discriminating"] for row in negative_controls)
    )
    if not complete:
        raise RuntimeError(
            "ACToR evaluation did not satisfy the sealed completeness contract"
        )
    contract_files = _publish_oracle_contracts(artifact_root, output_root)
    summary = {
        "schema_version": 1,
        "generated_at": C.utcnow_iso(),
        "campaign": "actor-li-absolute-micro",
        "artifact_commit": ARTIFACT_COMMIT,
        "rows": len(rows),
        "expected_rows": expected_rows,
        "measured": sum(
            row["evaluation_status"] == "measured" for row in rows
        ),
        "build_passed": sum(bool(row["build"]) for row in rows),
        "pass_all": sum(bool(row["pass_all"]) for row in rows),
        "safe_rust": sum(bool(row["safe_rust"]) for row in rows),
        "self_contained": sum(bool(row["self_contained"]) for row in rows),
        "safe_pass_all": sum(bool(row["safe_pass_all"]) for row in rows),
        "tests_passed": sum(int(row["tests_passed"]) for row in rows),
        "tests_expected": sum(int(row["expected_tests"]) for row in rows),
        "oracle_qualification": qualification["status"],
        "negative_control_subjects": len(negative_controls),
        "negative_control_discriminating_subjects": sum(
            row["discriminating"] for row in negative_controls
        ),
        "negative_control_tests_passed": sum(
            row["passed"] for row in negative_controls
        ),
        "negative_control_tests_expected": sum(
            row["expected_tests"] for row in negative_controls
        ),
        "published_oracle_contract_files": len(contract_files),
        "published_oracle_contract_subjects": len(
            {row["subject"] for row in contract_files}
        ),
        "sealed_cells": seal["cell_count"],
        "candidate_runtime_isolation": (
            "mount-pid-namespace-chroot-no-capabilities"
        ),
        "oracle_runtime_normalization": (
            "testcmp.sh CRLF/CR line endings converted to LF in temporary "
            "execution copies; published snapshots preserve artifact bytes"
        ),
        "complete": complete,
        "aggregate": aggregates[-1],
    }
    C.atomic_write_json(output_root / "summary.json", summary)
    C.atomic_write_json(
        output_root / "macro_experiment_status.json",
        {
            "schema_version": 1,
            "generated_at": C.utcnow_iso(),
            "artifact_commit": ARTIFACT_COMMIT,
            "subjects": list(MACRO_SUBJECTS),
            "subject_count": len(MACRO_SUBJECTS),
            "status": "blocked_reference_only",
            "reason": (
                "The paper's 57-program macro score is relative cross-testing "
                "between ACToR and coverage-baseline generated translations and "
                "their generated tests. The pinned artifact publishes source "
                "programs and evaluation machinery but neither output set nor a "
                "fixed independent macro oracle, so a CodeWeaver-only score "
                "would not reproduce that metric."
            ),
        },
    )
    return rows


def _write_matrix_summary(path: Path, results: list[dict[str, Any]]) -> None:
    counts: dict[str, int] = {}
    for result in results:
        status = str(result.get("status", "unknown"))
        counts[status] = counts.get(status, 0) + 1
    C.atomic_write_json(
        path,
        {
            "schema_version": 1,
            "generated_at": C.utcnow_iso(),
            "jobs": len(results),
            "by_status": counts,
            "results": results,
        },
    )


