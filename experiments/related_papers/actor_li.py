def _copy_seed_oracle(source: Path, destination: Path, name: str) -> None:
    destination.mkdir(parents=True)
    for filename in (
        "Makefile",
        f"{name}.c",
        "norm_rules.jsonl",
        "testcmp.sh",
        "tests00.jsonl",
    ):
        path = source / filename
        if not path.is_file():
            raise FileNotFoundError(path)
        shutil.copy2(path, destination / filename)
    _normalize_shell_scripts(destination)
    C.atomic_write_text(destination / "run-visible.sh", _visible_runner())
    (destination / "run-visible.sh").chmod(0o755)


def _assert_no_validation_leak(workspace: Path) -> None:
    forbidden = re.compile(r"^tests(?!00)\d{2}\.jsonl$")
    for path in workspace.rglob("*"):
        if not path.is_file():
            continue
        if forbidden.match(path.name) or "validation_tests" in path.parts:
            raise ValueError(f"withheld ACToR validation input leaked into {path}")


def prepare_campaign(
    *,
    artifact_root: Path,
    workspace_root: Path,
    force: bool = False,
) -> dict[str, Any]:
    _verify_clean_artifact(artifact_root)
    rows: list[dict[str, Any]] = []
    for subject in SUBJECTS:
        name = subject["name"]
        visible_source = artifact_root / "projects_input" / name
        validation_source = artifact_root / "validation_tests" / name
        if _jsonl_rows(visible_source) != subject["visible_tests"]:
            raise ValueError(f"{name}: released seed-test denominator drifted")
        if _jsonl_rows(validation_source) != subject["validation_tests"]:
            raise ValueError(f"{name}: validation-test denominator drifted")

        workspace = workspace_root / _subject_id(name)
        if workspace.exists():
            if not force:
                raise FileExistsError(workspace)
            shutil.rmtree(workspace)
        (workspace / "source").mkdir(parents=True)
        shutil.copy2(visible_source / f"{name}.c", workspace / "source" / f"{name}.c")
        scaffold = workspace / "scaffold"
        (scaffold / "src").mkdir(parents=True)
        C.atomic_write_text(scaffold / "Cargo.toml", _cargo_toml(name))
        C.atomic_write_text(scaffold / "src" / "main.rs", _main_rs(name))
        _copy_seed_oracle(visible_source, scaffold / "seed_oracle", name)
        (workspace / "licenses").mkdir()
        shutil.copy2(artifact_root / "LICENSE", workspace / "licenses" / "ACToR-MIT.txt")
        C.atomic_write_text(workspace / "brief.md", _brief(subject))
        C.atomic_write_text(workspace / "codeweaver.toml", _codeweaver_toml(subject))
        prepared = {
            "schema_version": 1,
            "prepared_at": C.utcnow_iso(),
            "campaign": "actor-li-absolute-micro",
            "subject": subject,
            "artifact_commit": ARTIFACT_COMMIT,
            "source_sha256": C.sha256_file(visible_source / f"{name}.c"),
            "visible_tests_sha256": C.sha256_file(
                visible_source / "tests00.jsonl"
            ),
            "visible_tests": subject["visible_tests"],
            "validation_tests": subject["validation_tests"],
            "validation_tree_sha256": _tree_sha256(validation_source),
            "validation_contract_excluded": True,
            "safe_rust_required": True,
        }
        C.atomic_write_json(workspace / "prepared.json", prepared)
        _assert_no_validation_leak(workspace)
        rows.append(
            {
                "id": _subject_id(name),
                "tool": "actor-li",
                "project": name,
                "source_language": "C",
                "target_language": "Rust",
                "visible_tests": subject["visible_tests"],
                "validation_tests": subject["validation_tests"],
                "prepared_dir": str(workspace),
            }
        )
    manifest = {
        "schema_version": 1,
        "generated_at": C.utcnow_iso(),
        "campaign": "actor-li-absolute-micro",
        "artifact_commit": ARTIFACT_COMMIT,
        "protocol": PROTOCOL,
        "projects": rows,
    }
    C.atomic_write_json(workspace_root / "manifest.json", manifest)
    return manifest


_RESULT_RE = re.compile(
    r"Results:\s+(\d+)\s+passed,\s+(\d+)\s+failed out of\s+(\d+)\s+tests"
)
_LOADED_RE = re.compile(r"Loaded\s+(\d+)\s+tests total")


def _parse_test_output(output: str) -> dict[str, int]:
    loaded = _LOADED_RE.search(output)
    result = _RESULT_RE.search(output)
    if not loaded or not result:
        return {"loaded": 0, "passed": 0, "failed": 0, "total": 0}
    passed, failed, total = (int(value) for value in result.groups())
    return {
        "loaded": int(loaded.group(1)),
        "passed": passed,
        "failed": failed,
        "total": total,
    }


def _write_command_log(root: Path, name: str, result: dict[str, Any]) -> None:
    metadata = {
        key: value for key, value in result.items() if key not in {"stdout", "stderr"}
    }
    C.atomic_write_json(root / f"{name}.json", metadata)
    C.atomic_write_text(root / f"{name}.stdout.log", result["stdout"])
    C.atomic_write_text(root / f"{name}.stderr.log", result["stderr"])


def qualify_oracles(
    *,
    artifact_root: Path,
    output_root: Path,
) -> dict[str, Any]:
    _verify_clean_artifact(artifact_root)
    rows: list[dict[str, Any]] = []
    for subject in SUBJECTS:
        name = subject["name"]
        source = artifact_root / "validation_tests" / name
        with tempfile.TemporaryDirectory(prefix=f"actor-li-{name}-oracle-") as temp:
            oracle = Path(temp) / name
            shutil.copytree(source, oracle)
            _normalize_shell_scripts(oracle)
            clean = C.run_command(["make", "clean"], cwd=oracle, timeout=120)
            build = C.run_command(["make", "all"], cwd=oracle, timeout=300)
            reference_binary = oracle / f"{name}.ref"
            compare = _sandboxed_comparison(
                binary=reference_binary,
                oracle=oracle,
                sandbox_root=Path(temp) / "sandbox",
                timeout=900,
            )
            log_root = output_root / "logs" / name
            _write_command_log(log_root, "clean", clean)
            _write_command_log(log_root, "build", build)
            _write_command_log(log_root, "sandboxed-self-comparison", compare)
            counts = _parse_test_output(compare["stdout"] + "\n" + compare["stderr"])
        expected = subject["validation_tests"]
        qualified = bool(
            build["returncode"] == 0
            and compare["returncode"] == 0
            and counts["loaded"] == expected
            and counts["total"] == expected
            and counts["passed"] == expected
            and counts["failed"] == 0
        )
        rows.append(
            {
                "subject": name,
                "expected_tests": expected,
                **counts,
                "build_returncode": build["returncode"],
                "comparison_returncode": compare["returncode"],
                "qualified": qualified,
                "candidate_runtime_isolated": True,
                "validation_tree_sha256": _tree_sha256(source),
            }
        )
    summary = {
        "schema_version": 1,
        "generated_at": C.utcnow_iso(),
        "artifact_commit": ARTIFACT_COMMIT,
        "subjects": len(rows),
        "expected_tests": sum(row["expected_tests"] for row in rows),
        "passed_tests": sum(row["passed"] for row in rows),
        "qualified_subjects": sum(row["qualified"] for row in rows),
        "status": "passed" if all(row["qualified"] for row in rows) else "failed",
        "rows": rows,
    }
    fields = list(rows[0])
    C.write_csv(output_root / "qualification.csv", rows, fields)
    C.atomic_write_json(output_root / "summary.json", summary)
    if summary["status"] != "passed":
        raise RuntimeError(f"ACToR oracle qualification failed: {summary}")
    return summary


def _publish_oracle_contracts(
    artifact_root: Path,
    output_root: Path,
) -> list[dict[str, Any]]:
    contracts = output_root / "oracle-contracts"
    if contracts.exists():
        shutil.rmtree(contracts)
    rows: list[dict[str, Any]] = []
    for subject in SUBJECTS:
        name = subject["name"]
        source = artifact_root / "validation_tests" / name
        destination = contracts / name
        shutil.copytree(source, destination)
        tree_hash = _tree_sha256(source)
        for path in sorted(item for item in destination.rglob("*") if item.is_file()):
            rows.append(
                {
                    "subject": name,
                    "relative_path": path.relative_to(contracts).as_posix(),
                    "bytes": path.stat().st_size,
                    "sha256": C.sha256_file(path),
                    "artifact_tree_sha256": tree_hash,
                }
            )
    C.write_csv(
        output_root / "oracle_contract_manifest.csv",
        rows,
        [
            "subject",
            "relative_path",
            "bytes",
            "sha256",
            "artifact_tree_sha256",
        ],
    )
    return rows


def _evaluate_negative_controls(
    *,
    artifact_root: Path,
    workspace_root: Path,
    output_root: Path,
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for subject in SUBJECTS:
        name = subject["name"]
        expected = subject["validation_tests"]
        with tempfile.TemporaryDirectory(
            prefix=f"actor-li-{name}-negative-"
        ) as temp:
            root = Path(temp)
            candidate = root / "candidate"
            oracle = root / "oracle"
            _copy_candidate_payload(
                workspace_root / _subject_id(name) / "scaffold",
                candidate,
            )
            shutil.copytree(
                artifact_root / "validation_tests" / name,
                oracle,
            )
            _normalize_shell_scripts(oracle)
            candidate_build = C.run_command(
                ["cargo", "build", "--release"],
                cwd=candidate,
                timeout=300,
                env={"CARGO_TERM_COLOR": "never"},
            )
            oracle_build = C.run_command(
                ["make", "all"],
                cwd=oracle,
                timeout=300,
            )
            comparison = _sandboxed_comparison(
                binary=(candidate / "target" / "release" / name),
                oracle=oracle,
                sandbox_root=root / "sandbox",
                timeout=900,
            )
            log_root = output_root / "negative-control-logs" / name
            _write_command_log(log_root, "candidate-build", candidate_build)
            _write_command_log(log_root, "oracle-build", oracle_build)
            _write_command_log(log_root, "hidden-comparison", comparison)
            counts = _parse_test_output(
                comparison["stdout"] + "\n" + comparison["stderr"]
            )
        rows.append(
            {
                "subject": name,
                "expected_tests": expected,
                **counts,
                "candidate_build_returncode": candidate_build["returncode"],
                "oracle_build_returncode": oracle_build["returncode"],
                "comparison_returncode": comparison["returncode"],
                "candidate_runtime_isolated": True,
                "discriminating": bool(
                    candidate_build["returncode"] == 0
                    and oracle_build["returncode"] == 0
                    and counts["loaded"] == expected
                    and counts["total"] == expected
                    and counts["passed"] < expected
                ),
            }
        )
    C.write_csv(
        output_root / "negative_controls.csv",
        rows,
        list(rows[0]),
    )
    if not all(row["discriminating"] for row in rows):
        raise RuntimeError(f"ACToR negative control failed: {rows}")
    return rows


def run_campaign(
    *,
    workspace_root: Path,
    runs_root: Path,
    repetitions: int = 3,
    jobs: int = 1,
    timeout: float | None = None,
    force: bool = False,
    resume_running: bool = False,
    retry_terminal: bool = False,
) -> list[dict[str, Any]]:
    if repetitions != PROTOCOL["repetitions"]:
        raise ValueError(
            f"ACToR requires exactly {PROTOCOL['repetitions']} repetitions"
        )
    seal = runs_root.parent / "evaluation" / CAMPAIGN_SEAL
    if seal.exists():
        raise RuntimeError(
            f"ACToR campaign is sealed by {seal}; use a new campaign root "
            "rather than exposing a scored campaign to additional model runs"
        )
    from experiments.recodeagent import run as runner

    manifest = C.read_json(workspace_root / "manifest.json")
    expected_ids = [_subject_id(subject["name"]) for subject in SUBJECTS]
    actual_ids = [row["id"] for row in manifest["projects"]]
    if actual_ids != expected_ids:
        raise ValueError("ACToR prepared manifest subject lock drifted")
    matrix = runner.build_job_list(["full"], expected_ids, repetitions)
    results = runner.run_matrix(
        matrix,
        workspace_root=workspace_root,
        runs_root=runs_root,
        protocol=PROTOCOL,
        timeout=timeout or float(PROTOCOL["agent_timeout_seconds"]),
        force=force,
        resume_running=resume_running,
        retry_terminal=retry_terminal,
        max_workers=max(1, jobs),
    )
    return results


