def _subject_id(name: str) -> str:
    return f"actor-li__{name}"


def _tree_sha256(root: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(item for item in root.rglob("*") if item.is_file()):
        relative = path.relative_to(root).as_posix().encode("utf-8")
        digest.update(len(relative).to_bytes(8, "big"))
        digest.update(relative)
        with path.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
    return digest.hexdigest()


def _verify_clean_artifact(repository: Path) -> None:
    C.verify_git_commit(repository, ARTIFACT_COMMIT)
    status = C.git_output(
        repository,
        "-c",
        "core.autocrlf=true",
        "status",
        "--porcelain=v1",
        "--untracked-files=all",
    )
    if status:
        raise ValueError(
            f"{repository}: ACToR artifact checkout is not clean; refusing "
            "to attribute modified bytes to the pinned commit"
        )


def _jsonl_rows(root: Path) -> int:
    count = 0
    for path in sorted(root.glob("tests[0-9][0-9].jsonl")):
        with path.open(encoding="utf-8") as handle:
            count += sum(bool(line.strip()) for line in handle)
    return count


def _normalize_shell_scripts(root: Path) -> None:
    for path in root.rglob("*.sh"):
        raw = path.read_bytes()
        path.write_bytes(raw.replace(b"\r\n", b"\n").replace(b"\r", b"\n"))
        path.chmod(path.stat().st_mode | 0o111)


