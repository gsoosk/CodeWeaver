def _repo_brief(subject: dict[str, Any]) -> str:
    return f"""\
# RepoTransBench reconstruction: {subject["name"]}

Translate the complete Python repository under `source/` to Java. The immutable
`scaffold/` contains the released Maven build and fixed Java test contract but
contains no released Java implementation. First copy it to `pipeline/target`;
create the production Java sources there.

## Hard constraints

- Preserve the source repository's behavior; do not edit `source/`.
- Do not weaken, delete, skip, mock, or rewrite the fixed tests.
- Use the released Maven/JUnit contract exactly as supplied.
- Run the configured build and all fixed tests before claiming success.
- This is an auditable historical `v1.0` Python-to-Java task. Do not claim that
  it represents the paper's currently advertised 1,897-repository release.
"""


def _rust_brief(subject: dict[str, Any], signature: str) -> str:
    return f"""\
# RustRepoTrans incremental task: {subject["name"]}

Implement exactly one missing Rust function in the immutable project scaffold:

```rust
{signature.strip()}
```

The source-language function and the paper-provided dependency context are
under `source/`. First copy `scaffold/` to `pipeline/target`, then replace only
the explicit `panic!("RustRepoTrans translation required")` body. Preserve all
other target code and public interfaces.

## Hard constraints

- Never edit `source/` or `scaffold/`.
- Do not weaken, delete, skip, mock, or rewrite any tests.
- Do not recover or search for the withheld golden Rust body.
- Run the configured full-project build and test suite before claiming success.
"""


def _git_archive_subtree(
    repository: Path, revision: str, subtree: str, destination: Path
) -> None:
    result = subprocess.run(
        ["git", "-C", str(repository), "archive", "--format=tar", revision, subtree],
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(result.stderr.decode("utf-8", errors="replace")[-4000:])
    parts_to_strip = len(Path(subtree).parts)
    destination.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(result.stdout), mode="r:") as archive:
        for member in archive.getmembers():
            parts = Path(member.name).parts
            if len(parts) <= parts_to_strip:
                continue
            relative = Path(*parts[parts_to_strip:])
            if relative.is_absolute() or ".." in relative.parts:
                raise ValueError(f"unsafe archive path: {member.name}")
            target = destination / relative
            if member.isdir():
                target.mkdir(parents=True, exist_ok=True)
                continue
            if not member.isfile():
                raise ValueError(f"unsupported archive member: {member.name}")
            target.parent.mkdir(parents=True, exist_ok=True)
            source = archive.extractfile(member)
            if source is None:
                raise ValueError(f"cannot read archive member: {member.name}")
            target.write_bytes(source.read())
            target.chmod(member.mode & 0o777)


def _copy_license(source_repository: Path, destination: Path) -> str:
    candidates = sorted(source_repository.glob("LICENSE*"))
    if not candidates:
        raise FileNotFoundError(f"license missing from {source_repository}")
    destination.mkdir(parents=True, exist_ok=True)
    copied = destination / candidates[0].name
    shutil.copy2(candidates[0], copied)
    return copied.name


def prepare_repotransbench(
    *,
    artifact_root: Path,
    reconstructed_sources: Path,
    workspace_root: Path,
    force: bool = False,
) -> dict[str, Any]:
    tag_commit = C.git_output(artifact_root, "rev-parse", "v1.0")
    if tag_commit != UPSTREAM_COMMITS["repotransbench_v1"]:
        raise ValueError(
            f"RepoTransBench v1.0 drifted: {tag_commit} != "
            f"{UPSTREAM_COMMITS['repotransbench_v1']}"
        )
    prepared_rows: list[dict[str, Any]] = []
    for subject in REPOTRANSBENCH_SUBJECTS:
        workspace = workspace_root / subject["id"]
        if workspace.exists():
            if not force:
                raise FileExistsError(workspace)
            shutil.rmtree(workspace)
        source_repository = reconstructed_sources / subject["source_directory"]
        C.verify_git_commit(source_repository, subject["source_commit"])
        C.copytree_clean(source_repository, workspace / "source")
        license_name = _copy_license(source_repository, workspace / "licenses")

        tree_path = f"repos/java_repos/{subject['target_tree']}"
        _git_archive_subtree(artifact_root, "v1.0", tree_path, workspace / "scaffold")
        production = workspace / "scaffold" / "src" / "main" / "java"
        released_files = sorted(production.rglob("*.java"))
        if not released_files:
            raise ValueError(f"released Java implementation absent for {subject['id']}")
        released_hashes = {
            path.relative_to(workspace / "scaffold").as_posix(): C.sha256_file(path)
            for path in released_files
        }
        for path in released_files:
            path.unlink()
        if list(production.rglob("*.java")):
            raise ValueError(f"golden Java implementation leaked for {subject['id']}")

        C.atomic_write_text(workspace / "brief.md", _repo_brief(subject))
        C.atomic_write_text(
            workspace / "codeweaver.toml",
            _codeweaver_toml(
                subject,
                source_language="Python",
                target_language="Java",
                build_command=["mvn", "-q", "-B", "-DskipTests", "package"],
                test_command=["mvn", "-q", "-B", "test"],
            ),
        )
        metadata = {
            "schema_version": 1,
            "prepared_at": C.utcnow_iso(),
            "campaign": "repotransbench",
            "subject": subject,
            "artifact_tag": "v1.0",
            "artifact_tag_commit": tag_commit,
            "released_target_tree": tree_path,
            "released_target_tree_oid": C.git_output(
                artifact_root, "rev-parse", f"v1.0:{tree_path}"
            ),
            "released_implementation_excluded": True,
            "released_implementation_hashes": released_hashes,
            "source_license_file": license_name,
            "oracle_expected_tests": subject["tests"],
            "current_release_status": "advertised GitHub asset returned HTTP 404",
            "historical_source_archive_status": "advertised Google Drive object unavailable",
        }
        C.atomic_write_json(workspace / "prepared.json", metadata)
        prepared_rows.append(
            {
                "id": subject["id"],
                "tool": "repotransbench",
                "project": subject["name"],
                "source_language": "Python",
                "target_language": "Java",
                "prepared_dir": str(workspace),
            }
        )
    manifest = {
        "schema_version": 1,
        "generated_at": C.utcnow_iso(),
        "campaign": "repotransbench",
        "projects": prepared_rows,
    }
    C.atomic_write_json(workspace_root / "manifest.json", manifest)
    return manifest


def _parse_task(task_path: Path) -> dict[str, str]:
    text = task_path.read_text(encoding="utf-8", errors="strict")
    halves = text.split("------", 1)
    if len(halves) != 2:
        raise ValueError(f"invalid task format: {task_path}")

    def extract(part: str) -> tuple[str, str]:
        path_match = re.search(r"<path>\s*(.*?)\s*</path>", part, re.DOTALL)
        function_match = re.search(
            r"<function>\s*(.*?)\s*</function>", part, re.DOTALL
        )
        if not path_match or not function_match:
            raise ValueError(f"invalid task section: {task_path}")
        return path_match.group(1).strip(), function_match.group(1).strip()

    target_path, target_function = extract(halves[0])
    source_path, source_function = extract(halves[1])
    opening = target_function.find("{")
    if opening < 0:
        raise ValueError(f"Rust target has no body: {task_path}")
    signature = target_function[:opening].rstrip()
    return {
        "target_path": target_path,
        "target_function": target_function,
        "target_signature": signature,
        "source_path": source_path,
        "source_function": source_function,
        "task_text": text,
    }


def _replace_function_with_stub(path: Path, target: str, signature: str) -> None:
    content = path.read_text(encoding="utf-8")
    candidates = [target]
    lines = target.splitlines()
    if lines:
        candidates.append("\n".join("    " + line if line else line for line in lines))
    matched = next((candidate for candidate in candidates if candidate in content), None)
    if matched is None:
        raise ValueError(f"golden target function not found in {path}")
    line_start = content.rfind("\n", 0, content.index(matched)) + 1
    indent_match = re.match(r"[ \t]*", content[line_start:])
    indent = indent_match.group(0) if indent_match else ""
    normalized_signature = signature.strip()
    stub = (
        f"{normalized_signature} {{\n"
        f'{indent}    panic!("RustRepoTrans translation required")\n'
        f"{indent}}}"
    )
    content = content.replace(matched, stub, 1)
    path.write_text(content, encoding="utf-8")


def _source_extension(language: str) -> str:
    return {"C": ".c", "Java": ".java", "Python": ".py"}[language]


def _assert_target_absent(workspace: Path, target: str) -> None:
    for path in workspace.rglob("*"):
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        if target in text:
            raise ValueError(f"golden target leaked into {path}")


def prepare_rustrepotrans(
    *,
    artifact_root: Path,
    workspace_root: Path,
    force: bool = False,
) -> dict[str, Any]:
    C.verify_git_commit(artifact_root, UPSTREAM_COMMITS["rustrepotrans"])
    pair_root = artifact_root / "Evaluate" / "function_pair_with_identical_functionality"
    dependency_root = (
        artifact_root / "Evaluate" / "related_functions_and_datatypes_and_import"
    )
    project_root = artifact_root / "Evaluate" / "projects"
    prepared_rows: list[dict[str, Any]] = []
    for subject in RUSTREPOTRANS_SUBJECTS:
        workspace = workspace_root / subject["id"]
        if workspace.exists():
            if not force:
                raise FileExistsError(workspace)
            shutil.rmtree(workspace)
        task_path = (
            pair_root
            / subject["project"]
            / subject["pair_directory"]
            / subject["task_file"]
        )
        dependency_path = (
            dependency_root
            / subject["project"]
            / subject["pair_directory"]
            / "rust"
            / subject["task_file"]
        )
        parsed = _parse_task(task_path)
        expected_suffix = subject["target_rel_path"].replace("\\", "/")
        if not parsed["target_path"].replace("\\", "/").endswith(expected_suffix):
            raise ValueError(f"target path drifted for {subject['id']}")
        dependencies = dependency_path.read_text(encoding="utf-8", errors="strict")
        source_project = project_root / subject["project"] / "rust"
        C.copytree_clean(source_project, workspace / "scaffold")
        target_file = workspace / "scaffold" / subject["target_rel_path"]
        _replace_function_with_stub(
            target_file, parsed["target_function"], parsed["target_signature"]
        )

        source_dir = workspace / "source"
        source_dir.mkdir(parents=True)
        C.atomic_write_text(
            source_dir / f"source_function{_source_extension(subject['source_language'])}",
            parsed["source_function"] + "\n",
        )
        contract = (
            "# Target signature\n\n```rust\n"
            + parsed["target_signature"].strip()
            + "\n```\n\n# Rust dependencies and data types\n\n```rust\n"
            + dependencies.strip()
            + "\n```\n"
        )
        C.atomic_write_text(source_dir / "target_contract.md", contract)
        license_candidates = sorted((workspace / "scaffold").glob("LICENSE*"))
        if not license_candidates:
            raise FileNotFoundError(f"target project license missing for {subject['id']}")
        licenses = workspace / "licenses"
        licenses.mkdir()
        shutil.copy2(license_candidates[0], licenses / license_candidates[0].name)
        C.atomic_write_text(
            workspace / "brief.md",
            _rust_brief(subject, parsed["target_signature"]),
        )
        C.atomic_write_text(
            workspace / "codeweaver.toml",
            _codeweaver_toml(
                subject,
                source_language=subject["source_language"],
                target_language="Rust",
                build_command=subject["build_command"],
                test_command=subject["test_command"],
            ),
        )
        _assert_target_absent(workspace, parsed["target_function"])
        metadata = {
            "schema_version": 1,
            "prepared_at": C.utcnow_iso(),
            "campaign": "rustrepotrans",
            "subject": subject,
            "artifact_commit": UPSTREAM_COMMITS["rustrepotrans"],
            "task_file_sha256": C.sha256_file(task_path),
            "dependency_file_sha256": C.sha256_file(dependency_path),
            "source_function_sha256": C.sha256_text(parsed["source_function"]),
            "golden_target_sha256": C.sha256_text(parsed["target_function"]),
            "golden_target_excluded": True,
            "target_signature": parsed["target_signature"],
            "negative_control_failed_tests": subject[
                "negative_control_failed_tests"
            ],
            "oracle_expected_tests": subject["expected_tests"],
        }
        C.atomic_write_json(workspace / "prepared.json", metadata)
        prepared_rows.append(
            {
                "id": subject["id"],
                "tool": "rustrepotrans",
                "project": subject["name"],
                "source_language": subject["source_language"],
                "target_language": "Rust",
                "prepared_dir": str(workspace),
            }
        )
    manifest = {
        "schema_version": 1,
        "generated_at": C.utcnow_iso(),
        "campaign": "rustrepotrans",
        "projects": prepared_rows,
    }
    C.atomic_write_json(workspace_root / "manifest.json", manifest)
    return manifest


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--campaign-root", required=True)
    parser.add_argument("--repotransbench-root", required=True)
    parser.add_argument("--repotransbench-sources", required=True)
    parser.add_argument("--rustrepotrans-root", required=True)
    parser.add_argument("--force", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    campaign_root = Path(args.campaign_root)
    campaign_root.mkdir(parents=True, exist_ok=True)
    repo_manifest = prepare_repotransbench(
        artifact_root=Path(args.repotransbench_root),
        reconstructed_sources=Path(args.repotransbench_sources),
        workspace_root=campaign_root / "repotransbench" / "workspaces",
        force=args.force,
    )
    rust_manifest = prepare_rustrepotrans(
        artifact_root=Path(args.rustrepotrans_root),
        workspace_root=campaign_root / "rustrepotrans" / "workspaces",
        force=args.force,
    )
    C.atomic_write_json(
        campaign_root / "preparation-summary.json",
        {
            "generated_at": C.utcnow_iso(),
            "protocol": PROTOCOL,
            "repotransbench": repo_manifest,
            "rustrepotrans": rust_manifest,
        },
    )
    print(
        f"prepared {len(repo_manifest['projects'])} RepoTransBench and "
        f"{len(rust_manifest['projects'])} RustRepoTrans subjects"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
